"""Step 9: write one draft file per item. Status is always needs_approval."""
from __future__ import annotations

import datetime as dt
from pathlib import Path

from .config import DRAFT_DIR
from .models import VerifiedItem
from .textutil import slugify


def week_folder(now: dt.datetime | None = None) -> str:
    now = now or dt.datetime.now(dt.timezone.utc)
    year, week, _ = now.isocalendar()
    return f"{year}-W{week:02d}"


def write_draft(
    vitem: VerifiedItem,
    variant_results: list,
    index: int,
    now: dt.datetime | None = None,
    draft_dir: Path | None = None,
) -> Path:
    """Write drafts/YYYY-Www/NN-slug.md for one item.

    Every passing variant is included. Validation and claim-check outcomes are
    written out as they happened, including failures.
    """
    base = (draft_dir or DRAFT_DIR) / week_folder(now)
    base.mkdir(parents=True, exist_ok=True)
    path = base / f"{index:02d}-{slugify(vitem.item.title)}.md"

    passing = [r for r in variant_results if r.passed]
    item = vitem.item

    lines: list[str] = [
        "---",
        'status: "needs_approval"',
        f'source_name: "{item.source_display}"',
        f'source_url: "{item.url}"',
        f'published: "{item.published}"',
        f"variants_passing: {len(passing)}",
        f"variants_attempted: {len(variant_results)}",
        f'variants_passing_ids: "{", ".join(r.variant_id for r in passing) or "none"}"',
        "---",
        "",
        f"# {item.title}",
        "",
        "> Draft for human approval. Nothing here is published automatically.",
        "",
    ]

    if passing:
        lines.append("## Caption variants")
        lines.append("")
        for result in passing:
            caption = result.caption
            attempts = len(result.attempts)
            retried = "" if attempts == 1 else f" after {attempts - 1} retry(ies)"
            lines += [
                f"### Variant {result.variant_id}",
                "",
                f"*Passed validation and the claim check on attempt "
                f"{attempts}{retried}.*",
                "",
                "```",
                caption.caption.strip(),
                "```",
                "",
                f"**Image text suggestion:** {caption.image_text.strip()}",
                "",
            ]
    else:
        lines += [
            "## Caption variants",
            "",
            "**None.** Every variant failed validation or the claim check "
            "within the retry budget. The failures are listed below.",
            "",
        ]

    lines += ["## Verified facts", ""]
    if vitem.facts:
        for n, fact in enumerate(vitem.facts, 1):
            lines += [f"{n}. **{fact.claim}**",
                      f'   - supporting quote: "{fact.quote}"', ""]
    else:
        lines += ["None verified.", ""]
    if vitem.facts_dropped:
        lines += [
            f"*{vitem.facts_dropped} extracted fact(s) were dropped because the "
            f"supporting quote was not found in the fetched article text.*", ""]

    lines += ["## Validation results", ""]
    for result in variant_results:
        verdict = "passed" if result.passed else "FAILED"
        lines.append(f"- **Variant {result.variant_id}: {verdict}** "
                     f"({len(result.attempts)} attempt(s))")
        for attempt in result.attempts:
            failures = attempt.get("failures") or []
            if failures:
                lines.append(f"  - attempt {attempt['attempt']}: "
                             f"{len(failures)} failure(s)")
                for f in failures:
                    lines.append(f"    - {f}")
            else:
                lines.append(f"  - attempt {attempt['attempt']}: passed")
    lines.append("")

    lines += [
        "## Source",
        "",
        f"- {item.source_display}: {item.url}",
        "",
        "---",
        "",
        "*Generated by rumah123-ig-weekly-generator. Status: needs_approval. "
        "No auto-posting.*",
        "",
    ]

    path.write_text("\n".join(lines))
    return path
