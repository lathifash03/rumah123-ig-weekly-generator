"""Evaluate a real run from run_log.json.

Reports first-attempt pass rate against pass rate after retries, counts per
failure type, and lists every failing case. Reads only what the run recorded,
so it cannot report a number the run did not produce.

Run:  python eval/run_eval.py
"""
from __future__ import annotations

import collections
import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "run_log.json"
OUT = ROOT / "eval" / "results.md"


def pct(num: int, den: int) -> str:
    return "n/a" if den == 0 else f"{100.0 * num / den:.0f}%"


def collect(log: dict) -> dict:
    variants = []
    for item in log.get("items", []):
        for variant in item.get("variants", []) or []:
            index = variant.get("variant_index")
            variants.append({
                "item_title": item.get("title", ""),
                "item_url": item.get("url", ""),
                "source": item.get("source", ""),
                "variant_index": index,
                "variant_id": variant.get("variant_id")
                or (chr(ord("A") + index) if isinstance(index, int) else "?"),
                "passed": bool(variant.get("passed")),
                "first_attempt_passed": bool(variant.get("first_attempt_passed")),
                "attempts": variant.get("attempts", []),
            })

    failure_counts = collections.Counter()
    first_attempt_failure_counts = collections.Counter()
    total_attempts = 0

    for variant in variants:
        for n, attempt in enumerate(variant["attempts"]):
            total_attempts += 1
            rules = attempt.get("failure_rules")
            if rules is None:
                # an attempt that errored before validation ran
                rules = ["generate_error"] if attempt.get("error") else []
            for rule in rules:
                failure_counts[rule] += 1
                if n == 0:
                    first_attempt_failure_counts[rule] += 1

    return {
        "variants": variants,
        "total_variants": len(variants),
        "first_attempt_passes": sum(1 for v in variants if v["first_attempt_passed"]),
        "final_passes": sum(1 for v in variants if v["passed"]),
        "failing": [v for v in variants if not v["passed"]],
        "failure_counts": failure_counts,
        "first_attempt_failure_counts": first_attempt_failure_counts,
        "total_attempts": total_attempts,
    }


def render(log: dict, stats: dict) -> str:
    total = stats["total_variants"]
    first = stats["first_attempt_passes"]
    final = stats["final_passes"]

    lines = [
        "# Evaluation of the real run",
        "",
        "Generated by `eval/run_eval.py` from `run_log.json`. Every number "
        "below comes from that log.",
        "",
        f"- Run started: `{log.get('run_started_utc')}`",
        f"- Run finished: `{log.get('run_finished_utc')}`",
        f"- Run status: `{log.get('status')}`",
        f"- Model: `{log.get('model')}`",
        f"- Duration: {log.get('duration_seconds')} s",
        "",
        "## Prompt versions",
        "",
        "| Prompt | sha256 (first 16) |",
        "| --- | --- |",
    ]
    for name, version in (log.get("prompt_versions") or {}).items():
        lines.append(f"| `{name}` | `{version}` |")

    counts = log.get("counts", {})
    lines += [
        "",
        "## Funnel",
        "",
        "| Step | Items |",
        "| --- | --- |",
        f"| Fetched inside the 7 day window | {counts.get('fetched_in_window', 'n/a')} |",
        f"| After keyword relevance | {counts.get('after_relevance', 'n/a')} |",
        f"| After dedupe | {counts.get('after_dedupe', 'n/a')} |",
        f"| Chosen by ranking | {counts.get('after_ranking', 'n/a')} |",
        f"| Drafts written | {counts.get('drafts_written', 'n/a')} |",
        "",
        "## Feeds",
        "",
        f"- Feeds fetched successfully: {len(log.get('feeds_ok', []))}",
        f"- Feeds failed: {len(log.get('feeds_failed', []))}",
    ]
    for feed in log.get("feeds_failed", []):
        lines.append(f"  - `{feed.get('name')}`: {feed.get('error')}")

    lines += [
        "",
        "## Fact extraction",
        "",
        "| Item | Facts verified | Facts dropped (quote not found) |",
        "| --- | --- | --- |",
    ]
    for item in log.get("items", []):
        title = (item.get("title") or "")[:60].replace("|", " ")
        lines.append(f"| {title} | {item.get('facts_verified', 0)} | "
                     f"{item.get('facts_dropped', 0)} |")

    lines += [
        "",
        "## Pass rate",
        "",
        "| Measure | Count | Rate |",
        "| --- | --- | --- |",
        f"| Variants attempted | {total} | - |",
        f"| Passed on the first attempt | {first} | {pct(first, total)} |",
        f"| Passed after retries (final) | {final} | {pct(final, total)} |",
        f"| Never passed | {total - final} | {pct(total - final, total)} |",
        "",
        f"Retries recovered {final - first} variant(s) that failed their first "
        f"attempt.",
        "",
        f"Total generate/validate attempts recorded: {stats['total_attempts']}.",
        "",
        "## Failures by type",
        "",
        "| Failure rule | Occurrences (all attempts) | On first attempt |",
        "| --- | --- | --- |",
    ]
    if stats["failure_counts"]:
        for rule, count in stats["failure_counts"].most_common():
            lines.append(
                f"| `{rule}` | {count} | "
                f"{stats['first_attempt_failure_counts'].get(rule, 0)} |")
    else:
        lines.append("| (none) | 0 | 0 |")

    lines += ["", "## Failing cases", ""]
    if not stats["failing"]:
        lines.append("None. Every variant passed within the retry budget.")
    else:
        for variant in stats["failing"]:
            lines += [
                f"### Variant {variant['variant_id']} - "
                f"{variant['item_title'][:70]}",
                "",
                f"- Source: {variant['source']}",
                f"- URL: {variant['item_url']}",
                f"- Variant: {variant['variant_id']}",
                f"- Attempts: {len(variant['attempts'])}",
                "- Failures on the final attempt:",
            ]
            final_attempt = variant["attempts"][-1] if variant["attempts"] else {}
            for failure in final_attempt.get("failures", []) or ["(none recorded)"]:
                lines.append(f"  - {failure}")
            lines.append("")

    tokens = log.get("tokens") or {}
    lines += [
        "## Tokens",
        "",
        f"- LLM calls: {tokens.get('calls', 'n/a')}",
        f"- Prompt tokens: {tokens.get('prompt_tokens', 'n/a')}",
        f"- Completion tokens: {tokens.get('completion_tokens', 'n/a')}",
        f"- Total tokens: {tokens.get('total_tokens', 'n/a')}",
        "",
        f"*Written {dt.datetime.now(dt.timezone.utc).isoformat()} by "
        f"`eval/run_eval.py`.*",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    if not LOG.exists():
        print(f"{LOG} does not exist. Run the pipeline first: python -m src.run",
              file=sys.stderr)
        return 2
    log = json.loads(LOG.read_text())
    stats = collect(log)
    OUT.write_text(render(log, stats))

    total, first, final = (stats["total_variants"], stats["first_attempt_passes"],
                           stats["final_passes"])
    print(f"variants: {total}")
    print(f"first-attempt pass rate: {first}/{total} ({pct(first, total)})")
    print(f"pass rate after retries: {final}/{total} ({pct(final, total)})")
    print(f"never passed: {total - final}")
    if stats["failure_counts"]:
        print("failures by type:")
        for rule, count in stats["failure_counts"].most_common():
            print(f"  {rule}: {count}")
    print(f"written: {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
